#!/usr/bin/env bash
# Fetch Hairer's codes, compile the reference driver against each, run every
# case, and write golden/hairer_reference/<method>_<case>.tsv.
#
# usage: emit_golden.sh [--from LOCAL_DIR]   (passed through to the fetch script)
set -euo pipefail

script_directory="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
rust_root="$(cd "${script_directory}/../.." && pwd)"
build_directory="${rust_root}/target/hairer_reference"
golden_directory="${rust_root}/golden/hairer_reference"

"${script_directory}/fetch_hairer_codes.sh" "$@" "${build_directory}"

# No -ffast-math, no -march=native, no FMA contraction: plain IEEE double.
flags=(-O2 -ffp-contract=off -fno-fast-math -cpp -std=legacy)
# The driver holds the right-hand sides. At -O1 and above gfortran fuses
# cos(x) and sin(x) of one argument into glibc sincos, which differs from
# separate cos and sin (and from Rust's f64::cos / f64::sin) in the last bit
# for about 0.07% of arguments. -O0 keeps the two calls separate.
driver_flags=(-O0 -ffp-contract=off -fno-fast-math -cpp)
cases=(
  arenstorf_tol1e-4
  arenstorf_tol1e-7
  arenstorf_tol1e-10
  arenstorf_backward_tol1e-7
  arenstorf_componentwise
  arenstorf_given_step
  prothero_robinson_stiff
)
compiler_version="$(gfortran --version | head -1)"

mkdir -p "${golden_directory}"
for method in dopri5 dop853; do
  source_file="${build_directory}/${method}.f"
  executable="${build_directory}/reference_${method}"
  macro="METHOD_$(echo "${method}" | tr '[:lower:]' '[:upper:]')"
  gfortran "${flags[@]}" -c "${source_file}" -o "${build_directory}/${method}.o"
  gfortran "${driver_flags[@]}" -D"${macro}" -J "${build_directory}" \
    -c "${script_directory}/reference_driver.F90" \
    -o "${build_directory}/reference_driver_${method}.o"
  gfortran "${build_directory}/reference_driver_${method}.o" \
    "${build_directory}/${method}.o" -o "${executable}"
  if nm "${executable}" | grep -q sincos; then
    echo "reference driver calls sincos; golden vectors would not match" >&2
    exit 1
  fi
  for case_name in "${cases[@]}"; do
    output="${golden_directory}/${method}_${case_name}.tsv"
    {
      echo "# generated by Cosmos/Rust/tools/hairer_reference/emit_golden.sh; do not edit"
      echo "# source	${method}.f	sha256	$(sha256sum "${source_file}" | cut -d' ' -f1)"
      echo "# driver	reference_driver.F90	sha256	$(sha256sum "${script_directory}/reference_driver.F90" | cut -d' ' -f1)"
      echo "# compiler	${compiler_version}"
      echo "# flags	${method}.f: ${flags[*]}; driver: ${driver_flags[*]} -D${macro}"
      "${executable}" "${case_name}"
    } > "${output}"
    echo "wrote ${output#"${rust_root}/"}  $(grep '^stats' "${output}")"
  done
done
